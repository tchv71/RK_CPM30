;EXTRN	PUTS	; FROM B0CONIO.ASM

SYSPG	EQU	0	; THE PAGE OF SYSTEM RAM
BDOSTRP EQU	5	;

DEF_DSK	EQU	4
IO_BYTE	EQU	3

	ds	bios-$
B_BASE::
;----------------------------------------------------
;	BIOS FUNCTION TABLE
	JMP	BOOT	; Cold boot of the system
WBOOT_ADR:
	JMP	WBOOT	; Warm boot of the system

	JMP	CON_ST;##;~~\
	JMP	 CONIN;##;---)- Console I/O
	JMP	CONOUT;##;__/		(see B0CONIO.ASM)

	JMP	LSTOUT;##;______  LST and AUX functions
	JMP	 PUNCH;##;  !		(see B0LSTAUX.asm)
	JMP	READER;##;_/!
;			   !
IFDEF DEBLOCK_ON_PICO
	JMP	HOME@ ;##;__!_________ Disk functions
	JMP	SELDSK;##;  !	 /	(see B2DISK.asm)
	JMP	SETTRK;##;  !	!
	JMP	SETREC;##;  !	!
	JMP	SETDMA;##;  !	!
	JMP	RD_REC;##;__!___/!
	JMP	WR_REC;##;  !	!
	JMP	LST_ST;##;_/	!
	JMP	SECTRN;##;______/
ELSE
	JMP	BIOS_HOME
	JMP	BIOS_SELDSK
	JMP	BIOS_SETTRK
	JMP	BIOS_SETSEC
	JMP	BIOS_SETDMA
	JMP	BIOS_READ
	JMP	BIOS_WRITE
	JMP	BIOS_PRSTAT
	JMP	BIOS_SECTRN
ENDIF

	JMP	SET_CONFIG
	JMP	DATE
;	JMP	ERR_READ
;	LXI	H,C_BASE+7CDH	; SPECIAL SUBROUTINE FOR CCP
;	MOV	A,M
;	CPI	2		; MODIFICATION
;	JZ	C_BASE+76BH
;	MVI	M,2
;	JMP	C_BASE+6D8H

DATE:
	push	d
	call	DispDate
	pop	d
	mov	a,c
	cpi	2dh
	jz	SetClock
	ret

DispDate:
	mov	a,c
	sui	2aH
	jz	CmdGetDate
	dcr	a ; 2bh
	jz	CmdSetDate
	dcr	a ; 2ch
	jz	CmdGetTime
	dcr	a ; 2dh
	jz	CmdSetTime
	mvi	A,0FFH
	ret

SET_CONFIG:
	XCHG
	LXI	D,VRAM
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H

	LXI	D,PPI
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H

	LXI	D,PPI2
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H

	LXI	D,DISP
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H

	LXI	D,DMA
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H

IFDEF PALM_CNTRL
	LXI	D,PALM_CNTRL
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H
ENDIF
	LXI	D,PPI3
	MOV	M,E
	INX	H
	MOV	M,D
	INX	H
	RET
.Z80
NC_DONT_EXEC	EQU	0F740h
NC_USERNO	EQU	0F741h
INBUFF		EQU	comlen-1
USERNO		EQU	usrcode
TDRIVE		EQU	4		;current drive name and user number.
INPOINT		EQU	comaddr
;ARG_DMA		EQU	dmaadr
IOBYTE		EQU	ioloc

BIOS_SHELL:
	LD	A, (NC_DONT_EXEC)
	OR	A

	;JP	 ccp_crlf
	JP	NZ, ccp_crlf

	; Запустить NC.COM с диска A:
	LD	HL, 4 OR ('A' SHL 8)
	LD	(INBUFF + 1), HL
	LD	HL, ':' OR ('N' SHL 8)
	LD	(INBUFF + 3), HL
	LD	HL, 'C'
	LD	(INBUFF + 5), HL

	; Сохранение текущего пользователя/папки
	LD	A, (USERNO)
	OR	0E0h
	LD	(NC_USERNO), A

	; Выбор нулевого пользователя/корневой папки
	LD	A, (TDRIVE)
	AND	0Fh
	LD	C, A
	JP	RUNCOMMAND
RUNCPM:
	XOR A
	LD	(INBUFF+1), A
RUNCOMMAND:
	LD  HL, INBUFF + 2
	LD  (INPOINT), HL
	LD	A,C
	LD	(TDRIVE),A
	LD	A,0C3h ; JMP OPCODE
	LD	(0),A
	LD	HL,WBOOT_ADR
	LD	(1),HL
	LD	(5),A
	LD	HL,D_BASE;FBASE
	LD	(6),HL
	LD	HL,TBUFF
	LD	(ARG_DMA),HL
	LD	A,81h
	LD	(IOBYTE),a
	JP	ccpstart;COMMAND

.8080
;------ FIRST TIME INITIALIZATION --------

BOOT:
	;JMP	0F86Ch

	MVI	a,80h
	@out	PALM_CNTRL

	LXI	h,VRAM
	SHLD	CHPNT
	LXI	H, SCR_W + (SCR_H SHL 8)
	SHLD	CURX
	MVI	A,04Fh
	STA	CURATR
	LXI	H, CursorShowed
	MVI	M,1
	INX	H
	INX	H
	INX	H
	INX	H
	XRA	A
	MOV	M,A
	INX	H
	MOV	M,A


	LXI	SP,C_BASE-100h
	CALL	DskInit;##
	;CALL	SETSCR
	CALL	SAV_SYS;##
;IFDEF	VDP9918
;	CALL	T_Reset
;ENDIF
	CALL	CLS
	CALL	SETSCR
	CALL	LOAD_FONT
	CALL	PRNT;##
	;DB	1FH
IFDEF	VDP9918
	DB	27,'[31m'
ENDIF
	DB	'CP/M-80 vers. 2.2'
IFDEF	VDP9918
	DB	27,'[97m'
ENDIF
	DB	0DH,0AH,'Copyright (C) 1980, Digital Research'
	DB	0DH,0AH,'BIOS vers. 3.2      (c) TCHV,1991-92'
	DB	",2023", 0DH, 0AH
IFDEF	USE_PRG_DC
IFDEF EXTERNAL_PORTS
	DB	"Palmira ProgDC in/out"
ELSE
	DB	"Palmira ProgDC"
ENDIF
ELSE
IFDEF	RK60K
	DB	"RK60K"
ELSE
	DB	"Palmira"
ENDIF
ENDIF
	DB	0DH,0AH,0

	lxi	h,DSKVER;##
	call	PUTS
	lxi	h,CONVER;##
	call	PUTS
	lxi	h,LSTVER;##
	call	PUTS
	CALL	SD_I
	XRA	A
	STA	DEF_DSK
	STA	IO_BYTE
	JMP	WBOOT2

WBOOT:	; WARM START OF CP/M BIOS - LOADING SYSTEM
	;JMP	0f86ch
	;DI
	LXI	SP,C_BASE-100h
	CALL	LOAD_FONT
WBOOT2:
	CALL	SD_I01
	MVI	C,0
IFDEF DEBLOCK_ON_PICO
	CALL	SELDSK
	CALL	HOME@
ELSE
	CALL	BIOS_SELDSK
	CALL	BIOS_HOME
ENDIF
WBT:	CALL	SETSCR;##
	CALL	LD_SYS;##

IFDEF	USE_PRG_DC
	LDA	NO_EI
	ORA	A
	JZ	WBT01
	XRA	A
	STA	NO_EI
	CALL	Init_IRQ
	EI
WBT01:
ENDIF
	LHLD	C_BASE
	MOV	A,L	; CHECK CP/M DISK PRESENCE
	CPI	0C3H
	JNZ	ASKDOS

	LXI	B,80H
IFDEF DEBLOCK_ON_PICO
	CALL	SETDMA;##
ELSE
	CALL	BIOS_SETDMA
ENDIF
	MVI	A,0C3H
	STA	SYSPG
	STA	BDOSTRP
	LXI	H,WBOOT_ADR
	SHLD	SYSPG+1
	LXI	H,D_BASE;##
	SHLD	BDOSTRP+1
	LDA	DEF_DSK
	MOV	C,A
	JMP	C_BASE;##

ASKDOS:	CALL	PRNT;##
	DB	10,13,'Ins DOS disk',0
	CALL	CONIN
	JMP	WBT



