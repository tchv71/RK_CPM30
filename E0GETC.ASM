;
;	E0GETC.ASM -	ED SC80  get symbol module (OS dependent)
;			RK version (hardware dependent)
;			Uses external PPI_ADR

?Ctrl	equ	40h
?Shift	equ	20h
REP_VAL	equ	50
RusLatLED equ	8

IFNDEF	PPI_ADR
;EXTRN	PPI_ADR
ENDIF

	DS	0F700h - $
	; F700h - 0F77Fh - gap for bios variables
	DS	80h
; Get character from console (returns in Acc)
GETCHR:
	PUSH	H
	PUSH	D
	PUSH	B
	LHLD	CharBufPtr
	MOV	A,H
	ORA	L
	JZ	GETCH01
	MOV	A,M
	ORA	A
	JZ	GETCH02
	INX	H
	SHLD	CharBufPtr
	;SUI	20h
	JMP	GETCHRET
GETCH02:
	LXI	H,0
	SHLD	CharBufPtr
GETCH01:
	CALL	GTC
	CALL	MODRUS
GETCHRET:
	POP	B
	POP	D
	POP	H
	RET
MODRUS:
	CPI	7FH
	RZ
	MOV	C,A
	@in	PPI+2
	MOV	B,A
	ANI	RusLatLED
	MOV	A,C
	JZ	EngTransl
	MVI	A,?Shift
	ANA	B
	JZ	MR07
	MOV	A,C
	CPI	'@'
	MVI	A,'"'
	RZ
MR07:
	MOV	A,C
	CPI	'^'
	MVI	A,':'
	RZ
	MOV	A,C
	CPI	'^'+20h
	JNZ	MR08
	SUI	20H
	MOV	C,A
MR08:
	CPI	'_'+80h
	MVI	A,'_'
	RZ
	MVI	A,?Shift
	ANA	B
	JNZ	MR05
	MOV	A,C
	CPI	'\'+80h
	MVI	A,'/'
	RZ
	MOV	A,C
MR02:	CPI	'.'
	MVI	A,','
	RZ
MR05:
	MOV	A,C
	CPI	'0'
	JC	MR04
	CPI	'9'+1
	JNC	MR04
	LXI	H,NUMSHIFT
	SUI	'0'
	MOV	E,A
	MVI	D,0
	DAD	D

	MVI	A,?Shift
	ANA	B
	MOV	A,C
	RNZ
	MOV	A,M
	RET
MR04:
	CPI	'@'+20h
	JNZ	$+5
	SUI	20H
	LXI	H,EK01
	CALL	QWC01
	JNZ	MR01
	CPI	40H
	RC
MR01:
	CPI	60H
	JNC	MR06
	ADI	80H
	CPI	0DFh
	RZ
	MOV	C,A
	MVI	A,?Shift
	ANA	B
	MOV	A,C
	RNZ
	ADI	20H
	RET
MR06:
	ADI	60H
	MOV	C,A
	MVI	A,?Shift
	ANA	B
	MOV	A,C
	RZ
	ADI	20H
	RET

; Get keyboard status A=0 - not pressed; A=0FFh - key pressed
GETST:
	MVI	A,0
	@out	PPI
	@in	PPI+1
	INR	A
	RZ
	CALL	GTVECT
	ORA	A
	RZ
	LDA	NREP
	ORA	A
	JZ	GETST0
	DCR	A
	MVI	A,0FFH
	RNZ
	LDA	WTREP
	DCR	A
	STA	WTREP
	JZ	GETST1
	XRA	A ; NREP == 1
	STA	NREP
	RET
GETST1:
	MVI	A,2
	STA	NREP
	MVI	A,0FFh
	RET
GETST0:
	MVI	A,REP_VAL
	STA	WTREP
	MVI	A,0FFH
	STA	ET1
	RET

WTREP:	DS	1

GTC:
	MVI	A,REP_VAL
	STA	WTREP

	LHLD	PNT
	MOV	A,M
	CPI	0FFH
	JZ	GTCH0
 	INX	H
	SHLD	PNT
	JMP	??RUS

GTCH0:	MVI	B,REP_VAL
RP3:	PUSH	B
	CALL	GTVECT
	POP	B
	ORA	A
	JZ	RP3
	LDA	NREP
	CPI	1
	JNZ	RP1
	XRA	A
	STA	NREP
	DCR	B
	JNZ	RP3
	INR	A
	STA	NREP
	LXI	H,ET1
	SHLD	PNT
	JMP	GTC
RP1:	LDA	NREP
	ORA	A
	JNZ	RP01
	LXI	H,ET1
RP02:	INX	H
	MOV	A,M
	CPI	0FFH
	JNZ	RP02
	SHLD	PNT
	PUSH	H
	CALL	MDEL
	POP	H
	DCX	H
	MOV	A,M
	JMP	??RUS

RP01:	CALL	MDEL
	LXI	H,ET1
	MOV	A,M
	INX	H
	SHLD	PNT
??RUS:	CPI	0FEH
	RNZ
	@in	PPI+2
	XRI	RusLatLED
	@out	PPI+2
	JMP	GTC

MDEL:
IF	0
	EI
	LXI	H,1000
RP2:	DCX	H
	MOV	A,H
	ORA	L
	JNZ	RP2
	DI
ELSE
	PUSH	B
	LXI	B,0808h
	;PUSH	H
	;LXI	H,PSG1+3
	MVI	A,36h
	@out	PSG1+3
	;MVI	L,0
	MOV	A,C
	;@out	PSG1
	;@out	PSG1
	;MOV	M,C
	;MOV	M,C
RP21:
	DCX	B
	MOV	A,B
	ORA	C
	JNZ	RP21
	;MVI	L,3
	;MVI	M,36
	MVI	A,36h
	@out	PSG1+3
	;POP	H
	POP	B
ENDIF
 	RET

; (ET1) - Pressed keys vector (in order of press)
; (NREP) - Repeat number
; Returns A = 0 - key not pressed A=0FFH - keys pressed
GTVECT:	MVI	B,5
GETC0:	PUSH	B
	LDA	@RD
	ORA	A
	MVI	A,0
	STA	@RD
	JNZ	$+6
	CALL	KBDSCN
	POP	B
	LXI	H,PRESS
	MOV	A,M
	CPI	0FFH
	JNZ	GTV04
	DCR	B
	JNZ	GETC0
	STA	ET1
	XRA	A
	RET
;	JMP	GTVECT

GTV04: 	LXI	H,ET2
	LXI	D,ET1
	PUSH	H
	PUSH	D
GTV08:	LDAX	D
	MOV	M,A
	INX	H
	INX	D
	CPI	0FFH
	JNZ	GTV08
	POP	D
	POP	H

GTV00:	MOV	A,M
	CPI	0FFH
	JZ	GTV06

	LXI	B,PRESS
GTV07:	LDAX	B
	CPI	0FFH
	JZ	GTV01
	CMP	M
	INX	B
	JNZ	GTV07
	MVI	M,0FDH
	STAX	D
	INX	D
	DCX	B
	MVI	A,0FDH
	STAX	B
	INX	B
GTV01:	INX	H
	JMP	GTV00

GTV06:	LXI	B,PRESS
	DCX	B
GTV10:	INX	B
	LDAX	B
	CPI	0FDH
	JZ	GTV10
	CPI	0FFH
	JZ	REP
	DCX	B
GTV11:	INX	B
	LDAX	B
	CPI	0FDH
	JZ	GTV11
	CPI	0FFH
	JZ	GTV22
	STAX	D
	INX	D
	JMP	GTV11
GTV22:	XRA	A
	STA	NREP
GTV21:	MVI	A,0FFH
	STAX	D
	RET

REP:	LDA	NREP
	ORA	A
	JZ	GTV31
	LXI	H,ET2
GTV30:	MOV	A,M
	INX	H
	CPI	0FFH
	JZ	GTV31
	CPI	0FDH
	JZ	GTV30
	XRA	A
	STA	NREP
	JMP	GTV21

GTV31:	LDA	NREP
	INR	A
	JZ	GTV21
	STA	NREP
	JMP	GTV21

; (PRESS) -  Pressed keys vector (in order of discover)
KBDSCN:	LXI	B,40H
	LXI	H,PRESS
	LXI	D,807FH

	PUSH	B
	@IN	PPI+2
	MOV	B,A
	LDA	@RUS
	ANA	B
	JNZ	$+6
	MVI	M,0FEH
	INX	H
	POP	B

NORM0:	CALL	?PRESS
	CZ	FOUND
	INR	B
	DCR	C
	JNZ	NORM0
	MVI	M,0FFH
	RET

?PRESS:	CALL	GETMSK
	MOV	A,E
	@out	PPI
	NOP
	NOP
	NOP
	@in	PPI+1
	ANA	D
	RNZ

	PUSH	H
	LXI	H,200
?PRES0:	@in	PPI+1
	ANA	D
	JNZ	?PRES1
	DCX	H
	MOV	A,H
	ORA	L
	JNZ	?PRES0
?PRES1:	POP	H
	RET


GETMSK:	MOV	A,D
	RLC
	MOV	D,A
	RNC
	MOV	A,E
	RLC
	MOV	E,A
	RET

FOUND:	PUSH	H
	PUSH	D
	PUSH	B
	MOV	A,B
	CPI	3FH
	JNZ	FND01
	MVI	A,20H
	JMP	FND02
FND01:	CPI	10H
	JC	FND03
	ADI	20H
	JMP	FND02
FND03:	MOV	E,B
	MVI	D,0
	LXI	H,KEYBRD
	DAD	D
	MOV	A,M
FND02:	MOV	E,A

	CPI	21H
	CNC	MODCHR
	MOV	A,E
	POP	B
	POP	D
	POP	H
	MOV	M,A
	INX	H
	RET

MODCHR:
	@in	PPI+2
	MOV	B,A
	ANI	RusLatLED
	JNZ	RusLatActive
MOD01:
	MOV	A,E
	CPI	40H
	JNC	MOD4
	CPI	3CH
	JNC	MOD3
MOD4:
	MVI	A,?Ctrl
	ANA	B
	JZ	SCTRL
	MVI	A,?Shift
	ANA	B
	JNZ	NoShiftEng
@SHIFT:
SH3:
	MOV	A,E
	CPI	7Fh
	JNZ	SH02
	SUI	20H
	MOV	E,A
	RET
SH02:
	CPI	40H
	RNC
	JMP	NoJcukTransl
@SHRUS:
	MOV	A,E
	CPI	7Fh
	JNZ	SHR02
	ADI	60H
	MOV	E,A
	RET
SHR02:
	CPI	':'
	MVI	E,'8'
	RZ
	CPI	'6'
	MVI	E,'?'
	RZ
	CPI	';'
	MVI	E,'+'
	RZ
	MOV	E,A
	CALL	CheckNoShift
	JZ	RLA01

	CPI	40h
	JNC	RLA01
SHR04:
	CALL	QwCukTransl
NoJcukTransl:
	CPI	07Fh
	RZ
	SUI	10H
	MOV	E,A
	CPI	20H
	RNZ
	MVI	E,5Fh
	RET

CheckNoShift:
	CPI	'2'
	RZ
	CPI	'3'
	RZ
	CPI	'4'
	RZ
	CPI	'7'
	RZ
	CPI	'<'
	RZ
	CPI	'>'
	RZ
	CPI	'?'
	RZ
	CPI	'='
	RET

MOD3:
	MVI	A,?Shift
	ANA	B
	JNZ	SH3
	MOV	A,B
	ANI	RusLatLED
	RZ
	JMP	RLA01


SCTRL:	MOV	A,E
	CPI	40H
	RC
	SUI	40H
	MOV	E,A
	RET

; RUS is activated
RusLatActive:
	MOV	A,E
	CPI	'@'
	RZ
	CPI	'^'
	RZ
	MVI	A,?Shift
	ANA	B
	JZ	@SHRUS
	MOV	A,E
	CPI	'='
	MVI	E,'-'
	RZ
	MOV	E,A
MOD40:
	MVI	A,?Ctrl
	ANA	B
	JZ	SCTRL
	MOV	A,E
	CPI	'2'
	RZ
	CPI	'7'
	RZ
RLA01:
	MOV	A,E
QwCukTransl:
	LXI	H,RUSKEY
QWC01:
	MOV	D, M
	INR	D
	;DCR	D
	RZ
	CMP	M
	INX	H
	INX	H
	JNZ	QWC01
	DCX	H
	MOV	A,M
	ORA	A
	MOV	E,A
	RET

NoShiftEng:
	MOV	A,E
	CPI	40h
	RC
	CPI	7Fh
	RZ
	MVI	A,20H
	ADD	E
	MOV	E,A
	RET
EngTransl:
	LXI	H,ENGKEY
	JMP	QWC01
	

KEYBRD:	DB	0CH,1FH,1BH,0,1,2,3,4
	DB	9,0AH,0DH
	DB	7FH; Here was 5FH
	DB	8,19H,18H,1AH
; Following map part may be done more compact algoritmically
; Decrease size by 27 bytes
;	DB	'0123456789:;<=>?'
;	DB	'@ABCDEFGHIJKLMNO'
;	DB	'PQRSTUVWXYZ[\]^ '
RUSKEY:
	DB 'QJ','WC','EU','RK','TE','YN','UG','I[','O]','PZ','[H',']_'
	DB 'AF','SY','DW','FA','GP','HR','JO','KL','LD',':','V'+20h,';V','\','\'+80H,'2','\'+20h,'7\'
	DB 'ZQ','X','^'+20h,'CS','VM','BI','NT','MX','>','@'+20h,'.', '@'+20h,'<B',',','B'+20h,'?.',0FFh

ENGKEY:
	DB "`@",'@`','^~','~^','\|','|\','{[','}]','[{',']}',27h,22h,22h,27h,0FFh
EK01:	
	27h,'\',22h,'\'-20h,'\'+80H,'\'+80H,0FFh

NUMSHIFT:	DB	')!"N;%:?*('
@RUS:	DB	80H
;@CTRL:	DB	?Ctrl
;@SHFT:	DB	?Shift
@RD:	DB	0

PNT:	DW	ET1
ET1:	DB	0ffh
	ds	9
	;DSEG
NREP:	DS	1
PRESS:	DS	10
ET2:	DS	10
IFNDEF	noend
;	END
ENDIF

