memcpy::
@01:
	MOV	A,C	; 5
	ORA	B	; 4
	JZ	@00	; 10
	LDAX	D	; 7
	INX	D	; 5
	MOV	M,A	; 7
	INX	H	; 5
	DCX	B	; 5
	JMP	@01	; 10 = 58
@00:
ENDIF

ENDIF
STK:	DS	2
HL_SAVE: DS	2


SD_I::
	;CALL	dblk_i
SD_I01:
	PUSH	H
	PUSH	D
	PUSH	B
	LXI	H,FNAME+4
	LDA	ARG_SELDSK
	STA	OLDDSK
	ADI	'A'
	MOV	M,A
	LXI	H, FNAME
	MVI	D,0
	CALL	CmdOpenDelete
	POP	B
	POP	D
	POP	H
	RET

SD_SEEK:
	LDA	BUFFER_DISK
	MOV	B,A
	LDA	OLDDSK
	CMP	B
	CNZ	SD_I01
	LDA	BUFFER_TRACK
	MOV	L,A
	MVI	H,0
	DAD	H
	DAD	H
	DAD	H
	MOV	D,H
	MOV	E,L
	DAD	H
	DAD	H
	LDA	BUFFER_DISK
	CPI	2
	JZ	SD_S02
	DAD	D ; hl = trk*1024*5*2/256
	JMP	SD_S03
SD_S02:
	DAD	H
SD_S03:
	MVI	D,0
	MOV	E,H
	MOV	H,L
	MOV	L,D
	XRA	A
	LDA	BUFFER_SECTOR ; A*512->BC
	;DCR	A
	;RAR
	RAL
	MOV	B,A
	;MVI	A,0
	;RAR
	;MOV	C,A
	MVI	C, 0
	DAD	B
	JNC	@cmp12
	INX	D
@cmp12:
	MVI	B,0
	JMP	CmdSeekGetSize

MEM_HI	equ	0dh 
FONT_ID	equ	10
FONT_RAM_WIN	equ	8000h

LOAD_FONT:
IFNDEF	RK60K
	DI
IFDEF USE_PRG_DC
	MVI	A,FONT_ID
	CALL	SET_PORTS_D8
ENDIF
	MVI	A,80H
	@out	PALM_CNTRL
	LXI	H,FONT
	MVI	D,0
	CALL	CmdOpenDelete
	ORA	A
	JNZ	ERR_READ

	LXI	D,FONT_RAM_WIN
	LXI	H,2048
	PUSH	D
	PUSH	H
	CALL	CmdRead
	POP	B
	POP	D

	ORA	A
	JNZ	ERR_READ
IFDEF USE_PRG_DC
	;MVI	A,FONT_ID
	;CALL	SET_PORTS_D8
	LXI	H,08000H
	LXI	D,08800h
	LXI	b,800H
	CALL	MEMCPY
ENDIF
IFDEF USE_PRG_DC
	MVI	A,MEM_HI;+10h
	CALL	SET_PORTS_D8
ENDIF
	MVI	A,0C0h
	@out	PALM_CNTRL
	;RET
	JMP	RET_SET_EI
ERR_READ:
	@SYSREG	0A0h
	MVI	A,4
	OUT	0E0H
	@SYSREG	80h
	JMP	0E000H
ELSE
	RET
ENDIF

MEMCPY:
	MOV	A,B
	ORA	C
	RZ
	MOV	A,M
	STAX	D
	INX	H
	INX	D
	DCX	B
	JMP	MEMCPY

IFDEF	USE_PRG_DC
SET_PORTS_D8:
	LXI	H,SET_PORTS1+1
	LXI	B, 08808h
	MOV	M,B
	PUSH	PSW
	@SYSREG	0A0H
	POP	PSW
	CALL	SET_PORTS1
	@SYSREG	80H
	RET

SET_PORTS1:
	OUT 0
	INR M
	DCR C
	RZ
	JMP SET_PORTS1
ENDIF

