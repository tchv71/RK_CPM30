IFDEF	RK60K
SAV_SYS::
	RET
LD_SYS::
	LXI	H,CPM_BIN
	MVI	D,0
	CALL	CmdOpenDelete
	LXI	D,0
	LXI	H,4+(CCP_START-100h)
	MVI	B,0
	CALL	CmdSeekGetSize

	LXI	D,C_BASE
	LXI	H,B_BASE-C_BASE;C_SIZE+D_SIZE
	CALL	CmdRead
	JMP	SD_I01

CPM_BIN:
	DS	64
ELSE
SAV_SYS::
	LXI	D,100h
	LXI	H,C_BASE+100h-CCP_START
	LXI	B,(CCP_START-100h)/4+1
	MVI	A,0C0H
	CALL	LD_S02

	LXI	D,C_BASE+100h-CCP_START
	LXI	H, 100H
	LXI	B, (BIOS_END-C_BASE + CCP_START-100h) / 4+1
	MVI	A,0C1H
	JMP	LD_S02

LD_SYS::
	LXI	H,C_BASE
	LXI	D,CCP_START
LD_S01:	LXI	B, (B_BASE-C_BASE) / 4 + 1
	MVI	A,0C1H
LD_S02:
	@out	PALM_CNTRL
	SHLD	HL_SAVE
	LXI	H,0
	DAD	SP
	SHLD	STK
	LHLD	HL_SAVE

	XCHG
	DI
	SPHL
	XCHG
	INR	B
@02:	REPT	2
	POP	D	; 10
	MOV	M,E	; 7
	INX	H	; 5
	MOV	M,D	; 7
	INX	H	; 5 = 34
	ENDM

	DCR	C	; 5
	JNZ	@02	; 10 = 49 / 2 bytes = 25 or (34 * 2 + 15)/4 = 21
	DCR	B
	JNZ	@02
	LHLD	STK
	SPHL

	MVI	A,0C0H
	@out	PALM_CNTRL
RET_SET_EI:
	PUSH	PSW
	LDA	NO_EI
	ORA	A
	JNZ	RSE01
	POP	PSW
	EI
	RET
RSE01:
	POP	PSW
	RET

IF	0
